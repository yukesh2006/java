package com.day4;

public class modulo {
	public static void main(String[] args) {
		int num=4;
		
		int remainder=num%2;
		System.out.println("Remainder: "+remainder);
		if(remainder==0) {
			System.out.println("Number is Even");
		}else {
			
			System.out.println("Number is odd");
		}
	}
}
